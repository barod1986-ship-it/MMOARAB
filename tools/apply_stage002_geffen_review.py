def first_csv_field(line: str) -> str:
    parsed = next(csv.reader(StringIO(line)))
    return parsed[0].lstrip("\ufeff") if parsed else ""


def insert_glossary_row(lines: list[str], row: str) -> None:
    english = first_csv_field(row).casefold()
    if any(first_csv_field(line).casefold() == english for line in lines[1:] if line.strip()):
        return
    for index in range(1, len(lines)):
        current = first_csv_field(lines[index]).casefold()
        if current and current > english:
            lines.insert(index, row)
            return
    lines.append(row)


