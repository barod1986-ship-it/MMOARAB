def read_preserved(path: Path) -> tuple[str, bool]:
    raw = path.read_bytes()
    bom = raw.startswith(b"\xef\xbb\xbf")
    return raw.decode("utf-8-sig" if bom else "utf-8"), bom


def write_preserved(path: Path, text: str, bom: bool) -> None:
    raw = text.encode("utf-8")
    path.write_bytes((b"\xef\xbb\xbf" if bom else b"") + raw)


def replace_one(text: str, old: str, new: str) -> str:
    count = text.count(old)
    if count == 1:
        return text.replace(old, new, 1)
    print(f"SKIP count={count}: {old[:70]}")
    return text


